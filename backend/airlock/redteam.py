router = APIRouter(prefix='/api/redteam', tags=['Deterministic red-team simulation'])


def _case_dict(case: Case) -> dict:
    return {'id': case.id, 'title': case.title, 'category': case.category,
            'description': case.description, 'trusted_task': case.trusted_task,
            'steps': len(case.events) + len(case.proposals) + 1,
            'expected_protected': case.expected_protected}


def simulate(case: Case, protected: bool) -> dict:
    intent = compile_trusted_intent(case.trusted_task)
    timeline = [{'stage': 'authority', 'label': 'Trusted user task', 'source': 'trusted_user',
                 'state': 'trusted', 'evidence': case.trusted_task[:220]}]
    memory = []
    for idx, event in enumerate(case.events, start=1):
        review = review_memory(event.content, event.source)
        if protected:
            state = review.state
            retained = contextualize(review, event.content)
            authority = False
        else:
            state = 'stored_without_memory_review'
            retained = event.content
            authority = False  # Even the baseline does not grant formal trusted-user provenance.
        memory.append({'id': review.record_id, 'source': event.source,
                       'state': state, 'indicators': list(review.indicators) if protected else [],
                       'in_context': bool(retained), 'authority_granted': authority,
                       'excerpt': event.content[:220]})
        timeline.append({'stage': 'memory', 'label': f'Step {idx}: {event.description}',
                         'source': event.source, 'state': state, 'evidence': event.content[:220],
                         'indicators': list(review.indicators) if protected else []})
    attempts = len(case.proposals)
    denied = 0
    outbox = []
    policies = []
    for idx, proposed in enumerate(case.proposals, start=1):
        tool = proposed.get('tool', '')
        args = proposed.get('args') or {}
        decision = authorize_fake_tool(intent, tool, args, used_actions=len(outbox))
        # Baseline matches the existing demo's permissive OFF behavior for the
        # fake send_email tool only. Unsupported tools are never executed.
        allowed = tool == 'send_email' and (not protected or decision.allowed)
        if allowed:
            outbox.append({'to': str(args.get('to', ''))[:100],
                           'subject': str(args.get('subject', ''))[:100]})
        else:
            denied += 1
        code = decision.code if protected else 'FIREWALL_OFF' if allowed else 'UNKNOWN_TOOL'
        policies.append({'step': idx, 'tool': tool, 'recipient': str(args.get('to', ''))[:100],
                         'allowed': allowed, 'code': code, 'source': 'scripted_proposal'})
        timeline.append({'stage': 'action', 'label': f'Scripted tool proposal {idx}',
                         'source': 'scripted_proposal', 'state': 'allowed' if allowed else 'denied',
                         'evidence': f'{tool} → {str(args.get("to", ""))[:100]} · policy: {code}',
                         'policy_code': code})
    compromised = any(not authorize_fake_tool(intent, 'send_email',
                    {'to': item['to'], 'subject': item['subject'], 'body': 'demo'},
                    used_actions=n).allowed for n, item in enumerate(outbox))
    return {'protected': protected, 'memory': memory, 'timeline': timeline,
            'policies': policies, 'attempts': attempts, 'denied': denied,
            'fake_outbox': outbox, 'unauthorized_fake_actions': compromised,
            'quarantined': sum(m['state'] == 'quarantined' for m in memory),
            'authority_source': 'trusted_user_task_only'}


def evaluate(case_id: str) -> dict:
    case = BY_ID.get(case_id)
    if not case:
        raise ValueError('Unknown case')
    off = simulate(case, False)
    on = simulate(case, True)
    output = {'case': _case_dict(case), 'off': off, 'on': on,
              'method': 'Deterministic scripted proposals on an ephemeral fake outbox. No LLM, browser, network, SMTP or persistent memory used.',
              'limitations': 'Memory indicator rules are incomplete; spoofing/encoding and adversarial paraphrases may evade detection. Simulated proposals do not establish how an LLM would behave.'}
    output['reproducibility_hash'] = sha256(json.dumps(output, sort_keys=True).encode()).hexdigest()[:20]
    return output


def matrix() -> dict:
    results = [evaluate(case.id) for case in CASES]
    return {'case_count': len(results), 'policy_expectations_met': sum(
            (('NO_ACTION' if not r['on']['policies'] else
              'ACTION_BUDGET' if r['case']['expected_protected'] == 'ACTION_BUDGET' and
                                 any(p['code'] == 'ACTION_BUDGET' for p in r['on']['policies']) else
              r['on']['policies'][-1]['code']) == r['case']['expected_protected']) for r in results),
            'memory_quarantines': sum(r['on']['quarantined'] for r in results),
            'protected_unauthorized_executions': sum(r['on']['unauthorized_fake_actions'] for r in results),
            'baseline_unauthorized_executions': sum(r['off']['unauthorized_fake_actions'] for r in results),
            'simulation_only': True, 'cases': [_case_dict(c) for c in CASES],
            'method': 'Scripted policy tests, not a live LLM security success rate'}


class EvalRequest(BaseModel):
    case_id: str


@router.get('/overview')
def overview_api():
    return matrix()


@router.post('/evaluate')
def evaluate_api(req: EvalRequest):
    if req.case_id not in BY_ID:
        raise HTTPException(status_code=404, detail='Unknown fixed simulation case')
    return evaluate(req.case_id)
