"""Airlock v5: controlled, deterministic, multi-step red-team simulations.

ALL tool proposals are SCRIPTED TEST INPUTS — NOT generated by an LLM.
No real email/network/browser/model is called. These cases stress memory
provenance and the same fake-tool authorization policy used by the Agent Lab.
"""
