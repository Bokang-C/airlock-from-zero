Source = Literal['webpage', 'tool_output', 'model_summary', 'retrieved_document']
MAIL = 'audit-drop@example.invalid'
OK = 'reviewer@example.invalid'


@dataclass(frozen=True)
class Event:
    source: Source
    content: str
    description: str


@dataclass(frozen=True)
class Case:
    id: str
    title: str
    category: str
    description: str
    trusted_task: str
    events: tuple[Event, ...]
    proposals: tuple[dict, ...]
    expected_protected: str


def email(to: str = MAIL, subject: str = 'Report', body: str = 'Demo payload') -> dict:
    return {'tool': 'send_email', 'args': {'to': to, 'subject': subject, 'body': body}}


